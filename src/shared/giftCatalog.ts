export function resolveGiftMapping(
  mappings: GiftEffectConfig[],
  giftId?: number | null,
  giftName?: string | null,
  diamondCount = 1
): GiftEffectConfig {
  // 1. Exact real TikTok giftId match (primary matching strategy)
  if (giftId) {
    const byId = mappings.find((m) => m.giftId === giftId && m.enabled);
    if (byId) return byId;
  }

  // 2. Fallback match by giftName (case-insensitive)
  if (giftName) {
    const normalized = giftName.trim().toLowerCase();
    const byName = mappings.find(
      (m) => m.giftName.toLowerCase() === normalized && m.enabled
    );
    if (byName) return byName;
  }

  // 3. Dynamic tier fallback by real diamondCount for any unmapped TikTok giftId
  if (diamondCount >= 10000) {
    return {
      id: `auto_legendary_${giftId || 0}`,
      giftId: giftId || 0,
      giftName: giftName || 'Legendary Gift',
      giftNameAr: giftName || 'هدية أسطورية',
      diamondCost: diamondCount,
      primaryEffect: 'legendary',
      secondaryEffects: ['3d_gift', 'golden_light', 'fireworks', 'cinematic_bg'],
      model3D: 'crown',
      use3D: true,
      primaryColor: '#FFD700',
      secondaryColor: '#7C3AED',
      scale: 1.35,
      durationMs: 7500,
      position: 'center',
      soundId: 'legendary_roar',
      priority: 4,
      enabled: true,
    };
  }
  if (diamondCount >= 500) {
    return {
      id: `auto_epic_${giftId || 0}`,
      giftId: giftId || 0,
      giftName: giftName || 'Epic Gift',
      giftNameAr: giftName || 'هدية مميزة',
      diamondCost: diamondCount,
      primaryEffect: 'golden_light',
      secondaryEffects: ['energy_waves', 'avatar_entrance', '3d_floating_text'],
      model3D: 'diamond',
      use3D: true,
      primaryColor: '#00D4FF',
      secondaryColor: '#7C3AED',
      scale: 1.15,
      durationMs: 5000,
      position: 'center',
      soundId: 'cosmic_drop',
      priority: 3,
      enabled: true,
    };
  }
  if (diamondCount >= 30) {
    return {
      id: `auto_rare_${giftId || 0}`,
      giftId: giftId || 0,
      giftName: giftName || 'Special Gift',
      giftNameAr: giftName || 'هدية خاصة',
      diamondCost: diamondCount,
      primaryEffect: 'flying_coins',
      secondaryEffects: ['confetti', 'gift_card'],
      use3D: false,
      primaryColor: '#FFD700',
      secondaryColor: '#00D4FF',
      scale: 1.05,
      durationMs: 3800,
      position: 'center',
      soundId: 'coins_cascade',
      priority: 2,
      enabled: true,
    };
  }

  return {
    id: `auto_std_${giftId || 0}`,
    giftId: giftId || 0,
    giftName: giftName || 'Gift',
    giftNameAr: giftName || 'هدية',
    diamondCost: diamondCount,
    primaryEffect: 'particle_explosion',
    secondaryEffects: ['gift_card'],
    use3D: false,
    primaryColor: '#7C3AED',
    secondaryColor: '#00D4FF',
    scale: 1.0,
    durationMs: 3000,
    position: 'center',
    soundId: 'gift_chime',
    priority: 1,
    enabled: true,
  };
}
